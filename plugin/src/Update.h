//
//	Update.h
//
//	プラグイン自身の入れ替え（自動アップデート）。ネイティブの Vectorworks ダイアログで
//	尋ね、実際のダウンロードと入れ替えは**同梱スクリプト**（macOS: vw-probes-update.sh /
//	Windows: vw-probes-update.ps1）に任せる。利用者が端末を開く必要は無い。
//
//	【なぜ要るか】このプラグインは**入れ替えが日常**である。確かめたい PR を変えるたびに
//	ビルドし直すので、そのたびに zip を落として展開して隔離フラグを外して……を手でやるのは
//	現実的でない。だから「新しいビルドがあるなら、押すだけで入れ替わる」ようにする。
//
//	【何を見て新旧を判断するか】**ビルド ID**。コミットではない——同じ main の sha から、
//	同居させる PR を変えて何度もビルドされるので、コミットで比べると「中身は別物なのに
//	最新扱い」になる。ID は**「何から作ったか」から計算する**（main のコミット＋各 PR の
//	head のハッシュ。scripts/gather-probes.sh）ので、**同じ顔ぶれで作り直しただけなら
//	変わらず、無駄に入れ替えを勧めない**（UpdateParse.h の Evaluate）。
//
//	【いつ走るか】入口は 1 つだけ——**ピッカーの先頭項目を選んだとき**
//	（RunManualUpdateCheck）。**起動時には確認しない**：起動のたびにネットワークを
//	叩けばその待ちが Vectorworks の起動に乗るうえ、入れ替えたくなるのは「新しいプローブを
//	走らせたい」ときであって、起動した瞬間ではない。本体（.vwpayload）だけの入れ替えなら
//	再起動が要らないので、**Vectorworks を動かしたままビルドを頼んで、その場で取り込んで
//	そのまま選べる**——だから起動時に尋ねる必要が無い。入れ替えの後にピッカーへ戻ってよいか
//	どうかは結末（UpdateOutcome）で返し、判断は ProbeMenu.cpp が行う。
//
//	【再起動が要るかは、何が変わったかで決まる】このプラグインは「殻（Vectorworks が起動時に
//	読み込むモジュール）」と「本体（殻が自分で読み込む .vwpayload）」に割れている
//	（plugin/src/PayloadAbi.h）。
//	  * **本体だけが新しい** … 置き換えるだけ。次にメニューを開いたときに読まれるので、
//	    **再起動は要らない**（これが日常の道）。
//	  * **殻まで変わった**   … まるごと入れ替えて「再起動しますか？」を尋ねる。
//	見分けるのは**殻の ID の一致**で、判断は UpdateParse.h の Evaluate が行う。判断できない
//	ときは必ず後者へ倒す——版の食い違ったまま動かすほうが危ない。
//
//	再起動を尋ねる場合、その再起動は**このプロセスからは行わない**（理由は UpdateParse.h の
//	「入れ替えたあとの再起動」）。
//

#pragma once

namespace vwprobe
{
	// 確認の結末。**呼び出し側が知りたいのは「この後も続けられるか」の 1 点**なので、
	// 何が起きたかではなくそれだけを返す（ProbeMenu.cpp はこれを見て、ピッカーへ戻るか
	// 打ち切るかを決める）。
	enum class UpdateOutcome
	{
		// このまま使い続けられる（最新だった・断った・失敗した・**本体だけ入れ替えた**）。
		// 本体だけの入れ替えは、次に本体を読むときから新しいものが動く。
		Continue,
		// 殻まで入れ替わった。再起動するまで動いているのは**古い殻**なので、そのまま
		// プローブを選ばせない（再起動を承知したかどうかに関わらず、こちらを返す）。
		RestartNeeded
	};

	// メニュー（ピッカーの先頭項目）から明示的に確認する。**唯一の入口**。
	// **最新だったときも・失敗したときも必ず結果を見せる**——利用者が自分で選んだ以上、
	// 無言で終わるのは「効かなかった」と区別が付かない。
	UpdateOutcome RunManualUpdateCheck();
} // namespace vwprobe
