//
//	Update.h
//
//	プラグイン自身の入れ替え（自動アップデート）。ネイティブの Vectorworks ダイアログで
//	尋ね、実際のダウンロードと入れ替えは**同梱スクリプト**（macOS: vw-probes-update.sh /
//	Windows: vw-probes-update.ps1）に任せる。利用者が端末を開く必要は無い。
//
//	【なぜ要るか】このプラグインは**入れ替えが日常**である。確かめたい PR を変えるたびに
//	ビルドし直すので、そのたびに zip を落として展開して隔離フラグを外して……を手でやるのは
//	現実的でない。だから「新しいビルドがあるなら、押すだけで入れ替わる」ようにする。
//
//	【何を見て新旧を判断するか】**ビルド ID（ワークフローの run id）**。コミットではない
//	——同じ main の sha から、同居させる PR を変えて何度もビルドされるので、コミットで
//	比べると「中身は別物なのに最新扱い」になる（UpdateParse.h の Evaluate）。
//
//	【いつ走るか】2 つの入口がある。
//	  * 起動時（RunStartupUpdateCheck）… プラグインの読み込み時に 1 度だけ。最新なら無言。
//	    コンパイル済みプラグインは**起動時にしか差し替わらない**ので、ここが本来の場所。
//	  * メニューから（RunManualUpdateCheck）… ピッカーの先頭項目で明示的に確認する。
//	    Vectorworks を動かしたままビルドを頼んだときに、**再起動 1 回**で新しいビルドへ
//	    移れる（起動時チェックだけだと、気付くのに 1 回・反映に 1 回で 2 回要る）。
//
//	どちらも成功したら「再起動しますか？」を尋ねる。入れ替えたビルドが実際に読み込まれるのは
//	次の起動時だからで、その再起動も**この プロセスからは行わない**（理由は UpdateParse.h の
//	「入れ替えたあとの再起動」）。
//

#pragma once

namespace vwprobe
{
	// 起動時のチェック。最新なら何も出さない。ネットワークが無ければ黙って諦める。
	// 1 セッションに 1 度だけ実行する（plugin_module_main は複数回呼ばれうる）。
	void RunStartupUpdateCheck();

	// メニュー（ピッカーの先頭項目）から明示的に確認する。起動時と違い、
	// **最新だったときも・失敗したときも必ず結果を見せる**——利用者が自分で押した以上、
	// 無言で終わるのは「効かなかった」と区別が付かない。
	void RunManualUpdateCheck();
} // namespace vwprobe
